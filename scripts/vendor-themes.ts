// Copy T3 Code's palettes into web/lib/themes.js, reduced to the roles this app's tokens use.
// Usage: node scripts/vendor-themes.ts [path to a T3 Code checkout]  (default ../t3code)
import { writeFileSync } from "node:fs";
import { join, resolve } from "node:path";
import { pathToFileURL } from "node:url";

const root = resolve(import.meta.dirname, ".."),
  t3 = resolve(process.argv[2] ?? join(root, "../t3code"));
type Colors = Record<string, string>;
type Definition = { id: string; label: string; appearance: "light" | "dark"; colors: Colors; variants?: Partial<Record<"light" | "dark", Colors>> };
const palettes = (await import(pathToFileURL(join(t3, "packages/shared/src/themePalettes.ts")).href)) as {
  BUILT_IN_THEMES: Definition[];
  T3_CODE_LIGHT_THEME_COLORS: Colors;
  T3_CODE_DARK_THEME_COLORS: Colors;
};

// T3 role -> factory token. Roles missing from T3 (success) are filled per appearance by the runtime.
const ROLES = {
  bg: "canvas",
  surface: "surface",
  "surface-2": "toolbarControlHover",
  ink: "text",
  muted: "textMuted",
  line: "border",
  accent: "accent",
  "accent-ink": "accentForeground",
  "accent-text": "updateForeground",
  attention: "warningForeground",
  danger: "errorForeground",
} as const;
const reduce = (c: Colors) => Object.fromEntries(Object.entries(ROLES).map(([token, role]) => [token, c[role]]));
const themes = [
  { id: "t3-code", label: "T3 Code", light: reduce(palettes.T3_CODE_LIGHT_THEME_COLORS), dark: reduce(palettes.T3_CODE_DARK_THEME_COLORS) },
  ...palettes.BUILT_IN_THEMES.map((t) => ({
    id: t.id,
    label: t.label,
    light: reduce(t.appearance === "light" ? t.colors : (t.variants?.light ?? t.colors)),
    dark: reduce(t.appearance === "dark" ? t.colors : (t.variants?.dark ?? t.colors)),
  })),
];
const out = join(root, "web/lib/themes.js");
writeFileSync(out, `// Generated by scripts/vendor-themes.ts from T3 Code's shared palettes. Do not edit.\nexport const T3_THEMES = ${JSON.stringify(themes, null, 2)};\n`);
console.log(`${out} <- ${themes.map((t) => t.id).join(", ")}`);
